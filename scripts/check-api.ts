import { appendFileSync, mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

import ts from "typescript";

const SOURCE = "dist/index.d.ts";
const REPORT = "api/party.js.d.ts";

const HEADER = `// This file is generated by scripts/check-api.ts. Do not edit it by hand.
//
// It lists the public API of party.js, as described by the type declarations in dist/index.d.ts,
// without doc comments and sorted by name. CI fails when a build no longer matches it.
//
// If you changed the API on purpose, run "bun run build && bun run api --update"
// and commit this file together with the change.
`;

/**
 * The name a top-level declaration is sorted by. The export list has none and goes last.
 */
function nameOf(statement: ts.Statement): string | undefined {
	if (ts.isVariableStatement(statement))
		return statement.declarationList.declarations[0]?.name.getText();
	if ("name" in statement && statement.name)
		return (statement.name as ts.Identifier).text;
	return undefined;
}

/**
 * Prints the public API as the bundled declarations describe it:
 * - without comments, so docs edits don't show up as API changes,
 * - declarations sorted by name, so moving code between files doesn't either,
 * - one export per line, so additions and removals diff cleanly.
 */
function printReport(dts: string): string {
	const file = ts.createSourceFile(
		SOURCE,
		dts,
		ts.ScriptTarget.Latest,
		true,
		ts.ScriptKind.TS,
	);
	const printer = ts.createPrinter({ removeComments: true });
	const print = (node: ts.Node) =>
		printer.printNode(ts.EmitHint.Unspecified, node, file);

	const declarations: { name: string; text: string }[] = [];
	const exports: string[] = [];

	for (const statement of file.statements) {
		if (
			ts.isExportDeclaration(statement) &&
			statement.exportClause &&
			ts.isNamedExports(statement.exportClause)
		) {
			exports.push(...statement.exportClause.elements.map(print));
			continue;
		}
		declarations.push({
			name: nameOf(statement) ?? "",
			text: print(statement),
		});
	}

	// stable sort, so overloads and merged declarations keep their order
	declarations.sort((a, b) => a.name.localeCompare(b.name));
	const bareName = (spec: string) => spec.replace(/^type /, "");
	exports.sort((a, b) => bareName(a).localeCompare(bareName(b)));

	const body = [
		...declarations.map((d) => d.text),
		`export {\n${exports.map((e) => `    ${e},`).join("\n")}\n};`,
	].join("\n\n");

	// the printer indents with 4 spaces, the repo with tabs
	return `${HEADER}\n${body.replace(/^((?: {4})+)/gm, (indent) => "\t".repeat(indent.length / 4))}\n`;
}

const actual = printReport(await Bun.file(SOURCE).text());

if (process.argv.includes("--update")) {
	await Bun.write(REPORT, actual);
	console.log(`Wrote ${REPORT}.`);
	process.exit(0);
}

const reportFile = Bun.file(REPORT);
const expected = (await reportFile.exists()) ? await reportFile.text() : "";
if (actual === expected) {
	console.log(`Public API matches ${REPORT}.`);
	process.exit(0);
}

const actualPath = join(
	mkdtempSync(join(tmpdir(), "partyjs-api-")),
	"party.js.d.ts",
);
await Bun.write(actualPath, actual);
const diff = Bun.spawnSync([
	"git",
	"diff",
	"--no-index",
	"--color=always",
	REPORT,
	actualPath,
]).stdout.toString();

console.error(
	`The public API changed:\n\n${diff}\nIf this is intended, run \`bun run api --update\` and commit ${REPORT}.`,
);
if (process.env.GITHUB_STEP_SUMMARY) {
	appendFileSync(
		process.env.GITHUB_STEP_SUMMARY,
		"### Public API\n\nThe public API changed. See the job log for the diff.\n",
	);
}
process.exit(1);
